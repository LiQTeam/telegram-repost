_VPN_CLIENT_FILE_EXTS = {"npvt", "nm"}


def _post_has_vpn_client_file(post) -> bool:
    for m in getattr(post, "media", None) or []:
        if getattr(m, "type", "") != "document":
            continue
        name = (getattr(m, "filename", "") or getattr(m, "url", "") or "").strip().lower()
        if not name:
            continue
        suffix_ext = name.rsplit(".", 1)[-1] if "." in name else ""
        if suffix_ext in _VPN_CLIENT_FILE_EXTS:
            return True
        tokens = set(re.findall(r"[a-z0-9]+", name))
        if _VPN_CLIENT_FILE_EXTS & tokens:
            return True
    return False


def post_has_config(post) -> bool:
    for attr in ("raw_text", "html_text"):
        val = getattr(post, attr, "") or ""
        if _CONFIG_RE.search(val):
            return True
    for m in getattr(post, "media", None) or []:
        name = getattr(m, "filename", "") or ""
        if name and _CONFIG_RE.search(name):
            return True
    if _post_has_vpn_client_file(post):
        return True
    return False


