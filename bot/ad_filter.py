def _llm_snippet(text: str, head: int = 1100, tail: int = 500) -> str:
    """برای پست‌های کوتاه، کلِ متن. برای پست‌های طولانی، *هم ابتدا هم انتهای* متن رو
    می‌فرسته (نه فقط ۱۵۰۰ کاراکترِ اول). دلیل: یک الگوی خیلی رایج در تبلیغاتِ
    پنهان اینه که یک خبر/متنِ کاملاً عادی بالای پست میاد و جمله‌ی تبلیغاتی (لینکِ
    عضویت، کد تخفیف، دعوتِ خرید و...) ته‌ی پست چسبونده می‌شه؛ اگه فقط از اول برش
    بخوریم، دقیقاً همون بخشِ تبلیغاتی که باید تشخیص داده بشه از دیدِ مدل حذف می‌شه."""
    if len(text) <= head + tail:
        return text
    return text[:head] + "\n...\n" + text[-tail:]


def _parse_llm_verdict(out: str) -> bool | None:
    """خروجیِ مدل رو پارس می‌کنه. فرمتِ ترجیحی «CHECK: ...\nVERDICT: AD/SAFE»
    است، ولی اگه مدل فرمتِ آزاد برگردوند (فقط یک کلمه)، هم‌چنان قابلِ‌فهمه.
    فقط دنبالِ خطِ VERDICT می‌گرده تا جمله‌ی CHECK (که ممکنه کلمه‌ی «تبلیغ» رو
    به‌عنوانِ توضیح داشته باشه، مثلِ «هیچ‌چیز - تبلیغ نیست») با AD/SAFE قاطی نشه."""
    if not out:
        return None
    verdict_line = out
    for line in out.splitlines():
        if "VERDICT" in line.upper():
            verdict_line = line
            break
    up = verdict_line.strip().upper()
    if "SAFE" in up:
        return False
    if "AD" in up:
        return True
    return None


def _parse_llm_confidence(out: str) -> bool:
    """می‌گرده دنبالِ خطِ CONFIDENCE. خروجی True یعنی اطمینانِ *پایین* (LOW) -
    یعنی حتی اگه با موتورِ قاعده‌محور هم‌نظر بود، ارزشِ گرفتنِ یک داورِ دومِ
    تاییدی رو داره (نگاه کن به classify_async). اگه مدل خطِ CONFIDENCE رو
    برنگردونه (فرمتِ آزاد/قدیمی یا مدلی که این دستور رو نادیده گرفته)، محافظه‌کارانه
    HIGH در نظر گرفته می‌شه - یعنی دقیقاً همون رفتارِ نسخه‌ی قبل (داورِ دوم فقط
    در صورتِ ناهم‌خوانی صدا زده می‌شه)، بدونِ اینکه نبودِ این خط چیزی رو خراب کنه."""
    if not out:
        return False
    for line in out.splitlines():
        if "CONFIDENCE" in line.upper():
            up = line.strip().upper()
            return "LOW" in up or "پایین" in line
    return False


