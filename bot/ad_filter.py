#  کشِ نتیجه‌ی داوریِ AI برای متن‌های تکراری (نگاه کن به docstringِ بالا، نسخه‌ی ۵)
# ===========================================================================
# کلید: (هشِ متنِ نرمال‌شده, نامِ داور/بازه‌ی مسیریابی). چون llm_classify دیگه به
# کلیدواژه‌های موتورِ قاعده حساس نیست (نسخه‌ی ۴)، نتیجه‌ی AI فقط تابعِ خودِ متن و
# داوره - پس یک کشِ سراسری (نه به‌ازایِ هر تنظیماتِ کاربر/مقصد) کاملاً صحیحه.
_llm_verdict_cache: "OrderedDict[str, tuple[bool | None, str, bool, float]]" = OrderedDict()
_llm_cache_lock = asyncio.Lock()


def _llm_cache_key(text: str, provider_bucket: str) -> str:
    digest = hashlib.sha256(_normalize(text).encode("utf-8")).hexdigest()
    return f"{provider_bucket}:{digest}"


async def _llm_cache_get(text: str, provider_bucket: str) -> tuple[bool, str, bool] | None:
    """اگه این متن (با همین داور) قبلاً بررسی شده و هنوز منقضی نشده، نتیجه‌ی
    ذخیره‌شده رو برمی‌گردونه؛ وگرنه None (یعنی باید واقعاً از AI پرسید)."""
    from . import config
    max_items = getattr(config, "AD_FILTER_CACHE_MAX_ITEMS", 0)
    ttl = getattr(config, "AD_FILTER_CACHE_TTL_SECONDS", 0)
    if max_items <= 0 or ttl <= 0:
        return None
    key = _llm_cache_key(text, provider_bucket)
    async with _llm_cache_lock:
        entry = _llm_verdict_cache.get(key)
        if not entry:
            return None
        verdict, check_line, low_conf, ts = entry
        if time.time() - ts > ttl:
            del _llm_verdict_cache[key]
            return None
        _llm_verdict_cache.move_to_end(key)
        return verdict, check_line, low_conf


async def _llm_cache_set(text: str, provider_bucket: str, verdict: bool, check_line: str, low_conf: bool) -> None:
    """نتیجه‌ی یک داوریِ *موفق* (verdict همیشه bool، نه None) رو کش می‌کنه.
    نتیجه‌ی None (یعنی AI در دسترس نبود/خطا داد) عمداً کش نمی‌شه - این یک
    وضعیتِ گذرا (شبکه/کلید)ست، نه یک تصمیم، و کش‌کردنش باعث می‌شه بعداً که AI
    دوباره در دسترس شد هم به‌اشتباه «در دسترس نبود» برگرده."""
    from . import config
    max_items = getattr(config, "AD_FILTER_CACHE_MAX_ITEMS", 0)
    ttl = getattr(config, "AD_FILTER_CACHE_TTL_SECONDS", 0)
    if max_items <= 0 or ttl <= 0:
        return
    key = _llm_cache_key(text, provider_bucket)
    async with _llm_cache_lock:
        if key in _llm_verdict_cache:
            del _llm_verdict_cache[key]
        elif len(_llm_verdict_cache) >= max_items:
            _llm_verdict_cache.popitem(last=False)  # قدیمی‌ترین (LRU) رو بردار
        _llm_verdict_cache[key] = (verdict, check_line, low_conf, time.time())


def llm_cache_stats() -> dict:
    """آمارِ خامِ کشِ داوری - برایِ دیباگ/نمایشِ اختیاری در منوی ادمین."""
    return {
        "items": len(_llm_verdict_cache),
    }


async def llm_classify(
    text: str, hint_keywords: list[str] | None = None, *, provider: str | None = None
) -> tuple[bool | None, str, bool]:
    """با LLM (Mistral/Groq از طریقِ AIRouter) تشخیص می‌ده پست تبلیغه یا نه، با
    خواندنِ کاملِ متن (نه فقط تطبیقِ کلمه). خروجی: (تصمیم, جمله‌یِ CHECK, اطمینانِ
    پایین؟). تصمیم: True=تبلیغ، False=عادی، None=در دسترس نبود/خطا (که یعنی باید
    به نتیجه‌ی موتورِ قاعده‌محور تکیه کرد). سومین مقدار (bool) یعنی خودِ مدل
    اطمینانِ پایینی به این تصمیم اعلام کرده - نگاه کن به classify_async که چطور
    این رو برایِ صدا زدنِ یک داورِ دومِ تاییدی استفاده می‌کنه، حتی وقتی با موتورِ
    قاعده‌محور هم‌نظر بوده (نسخه‌ی ۵).

    قبل از هر فراخوانیِ واقعیِ AI، یک کشِ سراسری (نگاه کن به _llm_cache_get/
    _llm_cache_set) چک می‌شه: اگه دقیقاً همین متن با همین داور قبلاً بررسی شده
    باشه، همون نتیجه بدونِ هیچ فراخوانیِ شبکه‌ای برگردونده می‌شه - چون تبلیغ‌ها
    اغلب کپیِ عینیِ هم‌دیگه‌ان، این هم در هزینه/تاخیر صرفه‌جویی می‌کنه و هم از
    تناقض (یه بار AD یه بار SAFE برای عیناً همون متن) جلوگیری می‌کنه.

    hint_keywords: عمداً دیگه سرنخِ اصلیِ تصمیم نیست (نگاه کن به classify_async) -
    مدل باید کاملاً مستقل و فقط با خواندنِ خودِ متن تصمیم بگیره، بدونِ اینکه
    کلیدواژه‌ی موتورِ قاعده‌محور روی داوریش سایه بندازه. اگه چیزی پاس داده بشه،
    صرفاً به‌عنوانِ یک «نکته‌ی جانبیِ کم‌اهمیت که ممکنه کاملاً بی‌ربط باشه» ذکر
    می‌شه، نه حکمِ قطعی.

    provider: اگه "mistral" یا "groq" باشه، دقیقاً همون سرویس (بدونِ مسیریابیِ
    خودکار) صدا زده می‌شه - برای گرفتنِ یک «نظرِ دومِ مستقل» از یک موتورِ متفاوت
    وقتی داوریِ اولِ AI با موتورِ قاعده‌محور ناهم‌خوان باشه یا اطمینانِ پایینی
    داشته باشه (نگاه کن به classify_async). اگه None باشه، مسیریابیِ خودکارِ
    AIRouter (که برای این وظیفه، Mistral - مدلِ قوی‌تر - رو در اولویت می‌ذاره)
    استفاده می‌شه. هیچ‌وقت استثنا پرتاب نمی‌کنه؛ اگه سرویسِ درخواستی کلید نداشته
    باشه یا خطا بده، None برمی‌گردونه."""
    text = (text or "").strip()
    if not text:
        return None, "", False
    provider_bucket = provider or "auto"
    cached = await _llm_cache_get(text, provider_bucket)
    if cached is not None:
        return cached
    try:
        from .config import MISTRAL_API_KEY, GROQ_API_KEY
        if not (MISTRAL_API_KEY or GROQ_API_KEY):
            return None, "", False
        from .ai_router import AIRouter
        router = AIRouter()
        try:
            snippet = _llm_snippet(text)
            hint_line = (
                f"(نکته‌ی جانبیِ کم‌اهمیت - ممکنه کاملاً بی‌ربط باشه، لازم نیست بهش "
                f"توجه کنی: یک فیلترِ ساده‌ی کلیدواژه‌ای این‌ها رو در متن دیده: "
                f"{'، '.join(hint_keywords[:6])}. خودت فقط با خواندنِ کاملِ متن و "
                f"فهمیدنِ نیتِ واقعیِ نویسنده تصمیم بگیر.)\n\n"
                if hint_keywords else ""
            )
            prompt = (
                f"{hint_line}متنِ پست:\n---\n{snippet}\n---\nاین پست را طبقِ قاعده‌های "
                f"بالا بررسی کن."
            )
            if provider == "mistral":
                out = await router._call_mistral(prompt, system_prompt=_LLM_SYSTEM, temperature=0.0)
            elif provider == "groq":
                out = await router._call_groq(prompt, system_prompt=_LLM_SYSTEM, temperature=0.0)
            else:
                out = await router.route(
                    prompt, task_type="ad_classify", system_prompt=_LLM_SYSTEM, temperature=0.0,
                )
        finally:
            try:
                await router.close()
            except Exception:  # noqa: BLE001
                pass
        if not out:
            return None, "", False
        check_line = ""
        for line in out.splitlines():
            if "CHECK" in line.upper():
                check_line = line.split(":", 1)[-1].strip()
                break
        verdict = _parse_llm_verdict(out)
        low_conf = _parse_llm_confidence(out)
        if verdict is not None:
            # فقط تصمیم‌های موفق کش می‌شن (نگاه کن به docstringِ _llm_cache_set).
            await _llm_cache_set(text, provider_bucket, verdict, check_line, low_conf)
        return verdict, check_line, low_conf
    except Exception as e:  # noqa: BLE001
        log.debug("داوریِ LLMِ تبلیغ ناموفق بود (به موتورِ قاعده‌محور تکیه می‌شود): %s", e)
        return None, "", False


_HEDGE_MARKERS = (
    "هیچ‌چیز", "هیچ چیز", "شاید", "احتمالا", "احتمالاً", "ممکنه", "ممکن است",
)


def _has_concrete_subject(check_line: str) -> bool:
    """موضوعِ مشخص یعنی: نه خالیه، نه صراحتاً می‌گه «هیچ‌چیز»، و نه یک هج/شکِ
    کلی («شاید»، «احتمالا»، «ممکنه»). عمداً از کلماتِ موضوعیِ عمومی مثلِ «خبر»/
    «سرگرمی»/«آگهی»/«نیست» به‌عنوانِ نشانه‌ی ردکردن استفاده نمی‌کنیم، چون این‌ها
    می‌تونن *داخلِ* یک توصیفِ کاملاً واقعی و مشخص هم بیان (مثلاً «یک آگهیِ جعلیِ
    استخدام برای کلاه‌برداری» خودش نوعی تبلیغ/کلاه‌برداریه ولی کلمه‌ی «آگهی» رو
    داره). همین‌طور «شک» رو تنها به‌شکلِ کلمه‌ی مستقل چک می‌کنیم، نه زیررشته، چون
    «شک» زیرمجموعه‌ی «مشکوک» هم هست و ممکنه باعثِ ردِ اشتباهِ جمله‌ای بشه که
    واقعاً موضوعِ مشخصی معرفی کرده (مثلاً «سایتِ مشکوکِ X»)."""
    if not check_line:
        return False
    if any(p in check_line for p in _HEDGE_MARKERS):
        return False
    if re.search(r"(?<![\u0600-\u06FF])شک(?![\u0600-\u06FF])", check_line):
        return False
    return True


async def classify_async(
    text: str,
    self_username: str,
    keywords: list[str],
    *,
    min_mentions: int = 3,
    min_links: int = 2,
    score_threshold: int = 4,
    use_llm: bool = True,
    config_source: str | None = None,
) -> tuple[bool, str, dict]:
    """تشخیصِ نهایی، حالا با یک لایه‌ی تصمیمِ سه‌گانه (موتورِ قاعده‌محور + دو
    داورِ AIِ مستقل) به‌جای اتکا به یک تصمیمِ تنها:

    ۱) اول موتورِ قاعده‌محور (برای سرعت و برای معافیتِ کانفیگ/پروکسی) - این‌جا
       صرفاً برای «آیا نشانه‌ای هست یا نه» استفاده می‌شه، نه به‌عنوانِ حکمِ نهایی.
    ۲) اگه use_llm=True و کلیدِ AI در دسترس باشه، اولین داورِ AI (که برایِ این
       وظیفه Mistral - مدلِ قوی‌تر - رو در اولویت می‌ذاره؛ نگاه کن به
       ai_router.route) با خواندنِ کاملِ متن و بدونِ دیدنِ کلیدواژه‌های موتورِ
       قاعده‌محور تصمیم می‌گیره - یعنی دیگه به کلمه‌های از پیش‌تعیین‌شده متکی
       نیست، بلکه خودش نیتِ متن رو می‌خونه.
    ۳) اگه این داوریِ اول با موتورِ قاعده‌محور *هم‌خوان* باشه (هر دو AD یا هر دو
       SAFE) و خودِ داورِ اول هم اطمینانِ بالایی اعلام کرده باشه، دو سرنخِ مستقل
       از هم به یک نتیجه رسیدن → همون نتیجه قبول می‌شه، بدونِ صرفِ فراخوانیِ
       اضافه.
    ۴) اگه *ناهم‌خوان* باشن، یا هم‌خوان باشن ولی داورِ اول خودش اطمینانِ پایینی
       اعلام کرده باشه (نگاه کن به CONFIDENCE در _LLM_SYSTEM؛ نسخه‌ی ۵) - یعنی
       دقیقاً همون‌جایی که امکانِ خطا هست، چه بلعیدنِ اشتباهِ یک پستِ عادی، چه رد
       نشدنِ یک تبلیغِ واقعی، چه هم‌نظریِ کم‌اطمینانِ کلیدواژه+داورِ اول در یک
       جهتِ اشتباه - یک داورِ AIِ دومِ *متفاوت* (موتورِ دیگه - Groq) هم مستقلاً
       همون متن رو می‌خونه:
         • اگه واقعاً ناهم‌خوانی بود (یا هم‌خوانیِ کم‌اطمینان ولی داورِ دوم هم
           تاییدش کرد)، تصمیمِ نهایی رأیِ اکثریتِ این سه سرنخه (۲ از ۳).
         • اگه هم‌خوانیِ کم‌اطمینان بود *و* داورِ دومِ مستقل مخالفت کرد، رأیِ
           اکثریت اصلاً معنی نداره (چون کلیدواژه و داورِ اول از قبل ۲ رأیِ
           هم‌جهت بودن و همیشه می‌بردن) - این‌جا حرفِ داورِ دومِ تازه و مستقل
           ملاک می‌شه، نه رأیِ اکثریت. این دقیقاً همون شکافیه که این نسخه می‌بنده.
       در هر دو حالت، نه یک کلیدواژه‌ی تنها می‌تونه پستِ عادی رو رد کنه، نه یک
       خطای تک‌مدلی می‌تونه یک تبلیغِ واقعی رو تبرئه کنه یا برعکس.
    ۵) اگه داورِ دوم در دسترس نبود (کلید/شبکه)، به تنها داورِ AIِ موجود تکیه
       می‌کنیم (رفتارِ قبلی: AI حرفِ آخر رو می‌زنه وقتی در دسترسه).
    اگه هیچ AIای در دسترس نبود، همون نتیجه‌ی موتورِ قاعده‌محور برمی‌گرده (هیچ
    پستی به‌خاطرِ نبودِ AI گم یا معطل نمی‌مونه).

    config_source: نگاه کن به docstringِ analyze() - نسخه‌ی HTMLِ پست، برای
    دیدنِ لینکِ کانفیگ/پروکسیِ پنهان‌شده پشتِ متنِ لینک (مثلِ «آواکادوپروکسی»)."""
    is_ad, reason, detail = analyze(
        text, self_username, keywords,
        min_mentions=min_mentions, min_links=min_links, score_threshold=score_threshold,
        config_source=config_source,
    )
    if detail.get("config"):
        # پستِ کانفیگ/پروکسیِ خالص - از قبل معاف شده، نیازی به AI نیست.
        return is_ad, reason, detail
    if not use_llm:
        return is_ad, reason, detail

    # داورِ اول: کاملاً مستقل، بدونِ دیدنِ کلیدواژه‌های موتورِ قاعده‌محور.
    verdict, check_line, low_conf = await llm_classify(text, hint_keywords=None)
    if verdict is None:
        # AI در دسترس نیست/خطا داد → به نتیجه‌ی موتورِ قاعده‌محور تکیه کن.
        return is_ad, reason, detail

    detail["llm"] = "AD" if verdict else "SAFE"
    detail["llm_check"] = check_line
    detail["rule_engine_verdict"] = is_ad
    detail["llm_confidence"] = "low" if low_conf else "high"

    if verdict == is_ad and not low_conf:
        # دو سرنخِ مستقل (کلیدواژه + خواندنِ انسان‌گونه‌ی AI، با اطمینانِ بالا)
        # به یک نتیجه رسیدن → بدونِ فراخوانیِ اضافه قبول می‌شه.
        reason = (reason + "؛ " if reason else "") + (
            ("داوریِ هوشِ مصنوعی: تبلیغ" if verdict else "داوریِ هوشِ مصنوعی: عادی")
            + (f" [{check_line}]" if check_line else "")
        )
        return verdict, reason, detail

    # به این‌جا از دو راه می‌رسیم: (الف) موتورِ قاعده‌محور و اولین داورِ AI
    # ناهم‌خوانن، یا (ب) هم‌خوانن ولی خودِ داورِ اول اطمینانِ پایینی اعلام کرده.
    # به‌جای اینکه فوراً حرفِ یکی رو قبول کنیم، یک داورِ دومِ *مستقل و از یک
    # موتورِ متفاوت* هم می‌پرسیم.
    agreed_low_confidence = (verdict == is_ad) and low_conf
    # داورِ اول از مسیریابیِ خودکار (که برایِ این وظیفه Mistral رو اولویت می‌ده)
    # اومد؛ داورِ دوم عمداً یک موتورِ *متفاوت* (Groq) است تا نظرش مستقل باشه.
    second_provider = "groq"
    verdict2, check_line2, _low_conf2 = await llm_classify(text, hint_keywords=None, provider=second_provider)
    detail["llm2"] = "AD" if verdict2 else ("SAFE" if verdict2 is False else "N/A")
    detail["llm2_check"] = check_line2

    if verdict2 is None:
        # داورِ دوم در دسترس نبود → به تنها داورِ AIِ موجود (اولین) تکیه می‌کنیم،
        # دقیقاً مثلِ رفتارِ قبلی وقتی فقط یک AI در دسترسه.
        note = (
            "داوریِ هوشِ مصنوعی (با اطمینانِ پایین، نتیجه‌ی موتورِ قاعده‌محور را "
            "تایید کرد؛ داورِ دومِ تاییدی در دسترس نبود): "
            if agreed_low_confidence else
            "داوریِ هوشِ مصنوعی (با خواندنِ کاملِ متن، نتیجه‌ی موتورِ قاعده‌محور "
            "را اصلاح کرد): "
        )
        reason = (reason + "؛ " if reason else "") + (
            note + ("تبلیغ" if verdict else "عادی") + (f" [{check_line}]" if check_line else "")
        )
        return verdict, reason, detail

    if agreed_low_confidence and verdict2 != verdict:
        # داورِ اول خودش به تصمیمی که با موتورِ قاعده هم‌نظر بود اطمینانِ کمی
        # داشت، و حالا یک داورِ دومِ کاملاً مستقل مخالفت می‌کنه. این‌جا رأیِ
        # اکثریتِ سه‌تایی معنی نداره: چون موتورِ قاعده و داورِ اول از اول با هم
        # «هم‌نظر» بودن (طبقِ تعریفِ همین شاخه)، رأیِ اکثریت همیشه ۲ به نفعِ
        # همون‌ها تموم می‌شد، حتی اگه داورِ دوم درست می‌گفت - یعنی صدا زدنش بدونِ
        # این استثنا هیچ فایده‌ای نداشت. برای همین دقیقاً همین‌جا، حرفِ داورِ
        # دومِ مستقل و تازه رو ملاک قرار می‌دیم؛ این همون گپیه که این نسخه می‌بنده.
        final = verdict2
        if final and not is_ad:
            # همون لایه‌ی کیفیتِ قبلی: اگه AD صرفاً از یک داورِ تنها میاد (نه
            # کلیدواژه)، باید بتونه دقیقاً بگه *چی* تبلیغ می‌شه.
            if not _has_concrete_subject(check_line2):
                final = False
        reason = (reason + "؛ " if reason else "") + (
            f"داوریِ اولِ AI (اطمینانِ پایین): {'تبلیغ' if verdict else 'عادی'}"
            + (f" [{check_line}]" if check_line else "")
            + f"؛ داورِ دومِ مستقل مخالفت کرد: {'تبلیغ' if verdict2 else 'عادی'}"
            + (f" [{check_line2}]" if check_line2 else "")
            + "؛ چون داورِ اول خودش مطمئن نبود، نظرِ داورِ دومِ تازه ملاک شد → نتیجه‌ی نهایی: "
            + ("تبلیغ" if final else "عادی")
        )
        detail["llm"] = "AD" if final else "SAFE"
        return final, reason, detail

    ad_votes = int(is_ad) + int(verdict) + int(verdict2)
    final = ad_votes >= 2

    # اگه نتیجه‌ی نهایی AD شد ولی موتورِ قاعده‌محور از اول هیچ نشانه‌ای پیدا نکرده
    # بود (یعنی این AD صرفاً از رأیِ دو AI میاد، نه از کلیدواژه)، به‌عنوانِ لایه‌ی
    # آخرِ کیفیت، حداقل یکی از دو داور باید بتونه دقیقاً بگه *چی* داره تبلیغ
    # می‌شه - «شاید تبلیغ باشه»ی هر دو مدل کافی نیست. اگه هیچ‌کدوم موضوعِ مشخصی
    # نگفتن، محافظه‌کارانه SAFE می‌مونیم (رفتارِ ایمن‌تر برای پستِ واقعی).
    if final and not is_ad:
        if not (_has_concrete_subject(check_line) or _has_concrete_subject(check_line2)):
            final = False

    if final == is_ad and final == verdict and final == verdict2:
        agree_note = "هر سه سرنخ (کلیدواژه + دو داورِ مستقلِ AI) هم‌نظر بودن"
    else:
        agree_note = f"رأیِ اکثریت از سه سرنخ (کلیدواژه/داورِ اول/داورِ دوم): {ad_votes} از ۳ رأیِ تبلیغ"
    reason = (reason + "؛ " if reason else "") + (
        f"داوریِ اولِ AI: {'تبلیغ' if verdict else 'عادی'}" + (f" [{check_line}]" if check_line else "")
        + f"؛ داوریِ دومِ AI: {'تبلیغ' if verdict2 else 'عادی'}" + (f" [{check_line2}]" if check_line2 else "")
        + f"؛ {agree_note} → نتیجه‌ی نهایی: {'تبلیغ' if final else 'عادی'}"
    )
    detail["llm"] = "AD" if final else "SAFE"
    return final, reason, detail


# ===========================================================================
#  فرمت‌بندیِ نمایشیِ دلیلِ فلگ (برای بنرِ صفِ تایید — نه برای لاگ)
# ===========================================================================
# reason خامِ بالا برای لاگ و دیباگ خوبه (یک رشته‌ی فشرده و کامل)، ولی مستقیم
# نشون‌دادنش به ادمین (همه‌چیز پشتِ سرِ هم، با «؛» جدا شده، توی یک پاراگراف)
# غیرقابلِ‌خوندنه؛ این تابع همون اطلاعات رو به چند خطِ کوتاه و مرتب می‌شکنه،
# هر سرنخ توی خطِ خودش، بدون این‌که منطقِ تشخیص (بالا) دست بخوره.
_REASON_LABELS: list[tuple[str, str]] = [
    ("نشانه‌ی قویِ تبلیغاتی:", "🔴"),
    ("چند واژه‌ی شرط‌بندی/قمار:", "🎰"),
    ("واژه‌ی شرط‌بندی همراهِ فراخوان/ثبت‌نام:", "🎰"),
    ("چند فراخوانِ اقدام:", "📣"),
    ("فراخوانِ اقدام همراهِ نشانه‌ی تجاری:", "📣"),
    ("چند نشانه‌ی تخفیف/پروموشن:", "🏷"),
    ("راهِ تماس همراهِ واژه‌ی سفارش/تبلیغ:", "☎️"),
    ("پست عمدتاً لیستِ منشن/لینک است", "🔗"),
    ("کلیدواژه‌ی سفارشیِ شما در متن پیدا شد:", "🔑"),
    ("واژه‌های مرتبط:", "🔹"),
    ("داوریِ هوشِ مصنوعی:", "🧠"),
    ("داوریِ اولِ AI", "🧠"),
    ("داوریِ دومِ AI", "🧠"),
    ("داوریِ اولِ AI (اطمینانِ پایین)", "🧠"),
    ("پستِ حاویِ کانفیگ/پروکسی است", "⚙️"),
]


def _label_for_clause(clause: str) -> str:
    for prefix, icon in _REASON_LABELS:
        if clause.startswith(prefix):
            return icon
    return "•"


def format_ad_flag_banner(reason: str, dest_title: str = "") -> str:
    """دلیلِ خامِ فیلترِ تبلیغات (reason، رشته‌ی «؛»-جداشده) رو به یک بنرِ تمیز،
    مرتب و خوانا برای پیش‌نمایشِ صفِ تایید تبدیل می‌کنه: هر سرنخ توی خطِ خودش،
    با یک آیکنِ کوچیک، بدونِ جمله‌های بلند و درهم. کپشنِ اصلیِ پست همیشه جدا
    (زیرِ همین بنر) نمایش داده می‌شه؛ این تابع فقط خودِ بنر رو می‌سازه.

    خروجی HTML آماده‌ی ارسال با ParseMode.HTML است؛ فقط تگ‌های ثابتِ خودِ این
    تابع (<b>) بدونِ escape می‌مونن - هر بخشی از متنِ خودِ reason (که می‌تونه
    شاملِ تکه‌ای از متنِ پست یا خروجیِ آزادِ AI باشه) قبل از چیده‌شدن escape
    می‌شه تا کاراکترهای </> از متنِ پست، ساختارِ HTMLِ پیام رو به‌هم نریزن."""
    from html import escape as _esc_local
    clauses = [c.strip() for c in (reason or "").split("؛") if c.strip()]
    if not clauses:
        return "🚩 <b>مشکوک به تبلیغاتی</b>"

    # آخرین بندی که با «نتیجه‌ی نهایی:» یا «→» تموم می‌شه، به‌عنوانِ خطِ جمع‌بندی
    # جدا می‌شه (اگه باشه)؛ بقیه به‌عنوانِ سرنخ‌های جداگانه لیست می‌شن.
    verdict_line = None
    if clauses and "نتیجه‌ی نهایی:" in clauses[-1]:
        verdict_line = clauses.pop().split("نتیجه‌ی نهایی:")[-1].strip()

    lines = ["🚩 <b>مشکوک به تبلیغاتی</b>"]
    if dest_title:
        lines.append(f"🎯 {_esc_local(dest_title)}")
    lines.append("┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄")
    for clause in clauses:
        icon = _label_for_clause(clause)
        lines.append(f"{icon} {_esc_local(clause)}")
    if verdict_line:
        lines.append("┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄")
        lines.append(f"⚖️ <b>نتیجه‌ی نهایی:</b> {_esc_local(verdict_line)}")
    return "\n".join(lines)
